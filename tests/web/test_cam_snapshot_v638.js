'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ui=fs.readFileSync('src/http/HttpServerWebUi.inc','utf8');
const transport=fs.readFileSync('src/http/HttpServerTransport.inc','utf8');
const cfg=fs.readFileSync('src/ConfigManager.cpp','utf8');
const start=ui.indexOf('async function openNewcamdModal()');
const end=ui.indexOf('  const clients = newcamdSettingsClients();',start);
assert.ok(start>=0&&end>start);
const code=ui.slice(start,end)+'  opened++;\n}';
const ctx=vm.createContext({opened:0,errors:0,camEditorClients:[],camEditorLoaded:false,camEditorLoading:false,caBackendUiText:(r)=>r,uiError:()=>ctx.errors++});
vm.runInContext(code,ctx);
(async()=>{
  const fixture={id:'fixture',backend_config:{user:'fixture-user',pass:'fixture-password'}};
  ctx.fetchJson=async(url,opts)=>{assert.equal(url,'/api/cam-client-settings');assert.equal(opts.cache,'no-store');return {result:'ok',cam_clients:[fixture]};};
  await ctx.openNewcamdModal();
  assert.equal(ctx.opened,1);assert.equal(ctx.camEditorLoaded,true);assert.equal(ctx.camEditorClients[0],fixture);
  ctx.fetchJson=async()=>{throw Error('timeout');};
  await ctx.openNewcamdModal();
  assert.equal(ctx.opened,1);assert.equal(ctx.camEditorLoaded,false);assert.equal(ctx.camEditorClients.length,0);
  ctx.fetchJson=async()=>({result:'ok'});
  await ctx.openNewcamdModal();assert.equal(ctx.opened,1);assert.equal(ctx.errors,2);
  ctx.fetchJson=async()=>({result:'ok',cam_clients:[]});
  await ctx.openNewcamdModal();assert.equal(ctx.opened,2);assert.equal(ctx.camEditorLoaded,true);
  const route=transport.indexOf('if (target == "/api/cam-client-settings" && req.method()==http::verb::get)');
  assert.ok(route>transport.indexOf('if (panelProtected && !apiKeyGranted && !isAuthorized(req)'));
  assert.match(transport.slice(route,route+1400),/no-store, private/);
  assert.match(transport.slice(route,route+1400),/savedCamClientsSnapshot/);
  assert.match(cfg,/bool ConfigManager::savedCamClientsSnapshot[\s\S]{0,200}lock\(fileMutex\)/);
  assert.match(ui,/if \(!camEditorLoaded \|\| camEditorLoading \|\| !document.getElementById\('newcamdRows'\)\)/);
  console.log('PASS CAM editor load/reopen/failure and protected GET wiring');
})().catch(e=>{console.error(e);process.exitCode=1;});
