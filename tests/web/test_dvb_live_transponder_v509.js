'use strict';
// V509: guard against regression: configured channels != active transponders;
// a live frontend must not be re-tuned merely to read its status.
const fs = require('node:fs');
const assert = require('node:assert/strict');
const rd=p=>fs.readFileSync(p,'utf8');
const api=rd('src/http/HttpServerDvbMedia.inc');
const tuner=rd('src/DvbSatellite.cpp');
const native=rd('src/media/LinuxDvbInput.cpp');
const ui=rd('src/http/HttpServerWebUi.inc');
const state=rd('src/http/HttpServerState.inc');
const gate=rd('src/http/TsdecryptViewerDecodeGate.h');
assert.match(api,/active_transponder_count/);
assert.match(api,/active_transponders/);
assert.match(api,/frontend_active/);
assert.match(api,/LinuxDvbInput::hasActiveFrontend/);
assert.match(api,/state->running\.load\(\) \|\| !state->active\.load\(\)/);
assert.match(api,/state->usingBackup/);
assert.match(ui,/activeCount/);
assert.match(ui,/activeTpCount/);
assert.match(ui,/uiBiText\('используется','active'\)/);
assert.match(ui,/uiBiText\('назначено','assigned'\)/);
assert.match(ui,/signal_for_active_tune/);
assert.match(ui,/TS ACTIVE/);
assert.match(ui,/dvb_transport_recent/);
assert.match(tuner,/if \(collectServices\) \{/);
assert.match(tuner,/result\["read_only"\] = true/);
assert.match(tuner,/result\["signal_for_active_tune"\] = true/);
assert.match(native,/frontendTransportActivity/);
assert.match(native,/stats\.transportRecent/);
assert.match(state,/dvb_lock_inferred_from_ts/);
assert.match(state,/dvb_frontend_lock_known/);
assert.match(api,/segmentExt == "\.ts"/);
assert.match(api,/segmentExt == "\.m4s"/);
assert.match(api,/mediaDelivered/);
assert.match(gate,/clientConnected && recentPes && recentOutput/);
assert.match(gate,/if \(gate\.promoted && recentPes && recentOutput\)/);
const vm = require('node:vm');
const firstScript=ui.indexOf('<script>');
const lastScript=ui.indexOf('</script>',firstScript);
assert.ok(firstScript>=0 && lastScript>firstScript,'embedded WebUI script');
assert.doesNotThrow(()=>new vm.Script(ui.slice(firstScript+8,lastScript)));
console.log('V509 active-transponder/LOCK and HLS client/CA state policy verified');
