'use strict';
// V593: browser and backend may restart ONE configured OSCam-mini reader only.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const manager=read('src/OscamMiniManager.cpp');
const header=read('src/OscamMiniManager.h');
const transport=read('src/http/HttpServerTransport.inc');
const vendor=read('third_party/oscam-mini/dvbstreamer5-reader-control.h');
const oscam=read('third_party/oscam-mini/oscam.c');
const control=read('src/OscamReaderControl.h');
const version=read('src/AppVersion.h');
const begin=manager.indexOf('<script>\nfunction normalizeLanguage');
assert.ok(begin>=0);
const end=manager.indexOf('</script>',begin);
assert.ok(end>begin);
new vm.Script(manager.slice(begin+8,end),{filename:'OSCamMiniV593.js'});
assert.match(manager,/async function restartOscamReader\(button\)/);
assert.match(manager,/data-reader="\$\{esc\(label\)\}"/);
assert.match(manager,/class="alt reader-restart"/);
assert.match(manager,/\/api\/oscam-mini\/reader-action/);
assert.match(manager,/action:'restart',label/);
for(const translation of ['Перезапустить ридер','Restart reader',
  'Ponovno pokreni čitač','Reader neu starten'])assert.ok(manager.includes(translation));
assert.match(manager,/const label=row\?\.dataset\.reader/);
assert.match(manager,/if\(!window\.confirm/);
assert.match(header,/readerActionJson\(const std::string& body\)/);
assert.match(transport,/target == "\/api\/oscam-mini\/reader-action"/);
assert.match(transport,/apiKeyAttempt \|\|/);
assert.match(transport,/isPanelSessionAuthorized\(req\)/);
const functionStart=manager.indexOf('OscamMiniManager::readerActionJson(');
const functionEnd=manager.indexOf('OscamMiniManager::renderPage()',functionStart);
const method=manager.slice(functionStart,functionEnd);
assert.ok(functionStart>0&&functionEnd>functionStart);
assert.match(method,/settings\.readers\.begin/);
assert.match(method,/!it->enabled/);
assert.match(method,/oscam_reader_control::restartReader\(label/);
assert.doesNotMatch(method,/systemctl restart|serviceActionJson|saveLocked\(/);
assert.match(vendor,/SO_PEERCRED/);
assert.match(vendor,/credentials\.uid != 0/);
assert.match(vendor,/chmod\(path, 0600\)/);
assert.match(vendor,/get_reader_by_label\(command \+ 8\)/);
assert.match(vendor,/add_job\(rdr->client, ACTION_READER_RESTART/);
assert.doesNotMatch(vendor,/systemctl|httpport|CONFIG_WEBIF/);
assert.match(oscam,/#include "dvbstreamer5-reader-control\.h"/);
assert.match(oscam,/dvbstreamer5_reader_control_worker/);
assert.match(control,/SOCK_SEQPACKET/);
assert.match(control,/validLabel\(label\)/);
assert.match(version,/kProgramVersion = "10\.8\.593"/);
console.log('PASS V593 OSCam-mini local-only selected-reader restart, RU EN HR DE, no full service restart');
