'use strict';
const fs=require('fs'), assert=require('assert/strict'), vm=require('vm');
const src=fs.readFileSync('src/http/HttpServerWebUi.inc','utf8');
const start=src.indexOf('function applyCaManagerSnapshot(');
const end=src.indexOf('function camClientOptions(',start);
assert.ok(start>=0&&end>start);
const ctx={language:'en',caManagerState:{clients:[]},lastCaBackendInventory:null,caManagerRefreshFailed:false,satEscape:String};
vm.createContext(ctx);
vm.runInContext(src.slice(start,end)+'\nthis.apply=applyCaManagerSnapshot;this.options=caBackendOptions;',ctx);
assert.match(ctx.options('tsdecrypt'),/status unknown/);
const loaded=[{id:'newcamd'},{id:'tsdecrypt',display_name:'TSDecrypt'}];
ctx.apply({ca_backend:{backends:loaded}});
assert.match(ctx.options('tsdecrypt'),/TSDecrypt \/ plugin/);
ctx.apply({ca_backend:{busy:true,backends:[{id:'passthrough'}]}});
assert.match(ctx.options('tsdecrypt'),/TSDecrypt \/ plugin/);
ctx.apply({ca_backend:{busy:true,backends_cached:true,backends:loaded}});
assert.match(ctx.options('tsdecrypt'),/TSDecrypt \/ plugin/);
ctx.apply({ca_backend:{backends:[]}});
assert.match(ctx.options('tsdecrypt'),/not loaded/);
ctx.caManagerRefreshFailed=true;
assert.match(ctx.options('tsdecrypt'),/status unknown/);
console.log('PASS CA UI inventory, busy fallback and unknown state');
