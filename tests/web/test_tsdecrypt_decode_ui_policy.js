// V501: CI regression for honest TSDecrypt decode indication and portable packaging.
const fs = require('node:fs');
const assert = require('node:assert/strict');
const read = p => fs.readFileSync(p, 'utf8');
const state = read('src/http/HttpServerState.inc');
const smooth = read('src/http/HttpServerCommon.inc');
const ui = read('src/http/HttpServerWebUi.inc');
const pack = read('scripts/make_portable_linux_bundle.sh');
const builder = read('scripts/build_tsdecrypt_icam.sh');
const workflow = read('.github/workflows/build-main-linux.yml');
const version = read('src/AppVersion.h');
assert.match(version, /kProgramVersion = "10\.8\.501"/);
assert.match(state, /cam\.backendId == "tsdecrypt"/);
assert.match(state, /tsdecryptClient && rawCaDecodeState == "clear"/);
assert.match(state, /rawCaDecodeState = "unverified"/);
assert.match(state, /streamActive, !tsdecryptClient/);
assert.match(smooth, /if \(!allowClearHold\)/);
const start = ui.indexOf('function caDecodeInfo(stream)');
const end = ui.indexOf('\nfunction formatEpgClock', start);
assert.ok(start >= 0 && end > start, 'CA UI function found');
const caInfo = ui.slice(start, end);
assert.match(caInfo, /mode === 'unverified'/);
assert.match(caInfo, /cls:'waiting'/);
assert.match(caInfo, /playback unverified/);
assert.match(caInfo, /mode === 'clear'.*cls:'clear'/);
assert.match(pack, /--with-tsdecrypt/);
assert.match(pack, /build_tsdecrypt_icam\.sh/);
assert.match(pack, /\$BUILD_DIR\/tsdecrypt-icam\/tsdecrypt/);
assert.match(builder, /submodule\.libfuncs\.url=https:\/\/github\.com\/gfto\/libfuncs\.git/);
assert.match(builder, /submodule\.libtsfuncs\.url=https:\/\/github\.com\/gfto\/libtsfuncs\.git/);
assert.match(workflow, /Build pinned iCAM TSDecrypt/);
assert.match(workflow, /--with-tsdecrypt/);
console.log('TSDecrypt V501 decode UI / portable policy verified');
