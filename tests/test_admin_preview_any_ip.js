'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const server=read('src/http/HttpServerTransport.inc');
const common=read('src/http/HttpServerCommon.inc');
const player=read('web/preview/preview-player.js');
const authAt=server.indexOf('const bool panelProtected = requiresAuthentication(target)');
const headAt=server.indexOf('if (req.method() == http::verb::head)');
const getAt=server.indexOf('if (req.method() == http::verb::get)',headAt);
assert.ok(authAt>0&&headAt>authAt&&getAt>headAt,'panel auth precedes preview');
assert.match(server.slice(authAt,headAt),/isPanelSessionAuthorized\(req\)/);
assert.match(common,/if \(target\.rfind\("\/api\/", 0\) == 0\) return true;/);
assert.match(common,/bool resolvePrivatePreviewHlsTarget\(/);
assert.match(common,/cleanHlsRelativePath\(name\) != name/);
const marker=server.indexOf('if (safeId && active)');
const manifest=server.slice(marker,server.indexOf('manifest["sources"]',marker));
assert.ok(marker>0);
assert.match(manifest,/"private-http"/);
assert.match(manifest,/"private-hls"/);
assert.match(manifest,/"\/preview\.ts"/);
assert.match(manifest,/"\/preview\.hls\/video\.m3u8"/);
assert.doesNotMatch(manifest,/"\/stream\/"/);
assert.doesNotMatch(manifest,/hlsPublicName\(/);
const privateHls=server.slice(getAt,server.indexOf('std::string previewId;',getAt));
assert.match(privateHls,/resolvePrivatePreviewHlsTarget\(/);
assert.match(privateHls,/"\/hls\/" \+ privateHlsId/);
assert.match(privateHls,/serveHlsFile\(/);
assert.doesNotMatch(privateHls,/isStreamClientAllowed\(/);
assert.match(server.slice(getAt),/if \(!isStreamClientAllowed\(socket, target, req\)\)/);
assert.match(player,/credentials: 'same-origin'/);
assert.match(player,/\/api\/streams\//);
console.log('V507 private admin preview HTTP/HLS independent of subscriber IP');
